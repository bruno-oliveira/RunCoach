RACE_PROFILES: Dict[float, RaceProfile] = {
    5.0:  _5K,
    10.0: _10K,
    21.1: _HALF,
    30.0: _30K_TRAIL,
    42.2: _MARATHON,
}


def lookup_profile(target_distance: float) -> RaceProfile:
    """Return the closest matching road race profile by distance.

    Snaps to the nearest registered profile; for arbitrary trail/ultra
    distances the caller should route to the trail-protocol path before
    reaching this lookup.
    """
    closest_distance = min(RACE_PROFILES.keys(), key=lambda d: abs(d - target_distance))
    return RACE_PROFILES[closest_distance]
