"""Per-distance race profiles for the road race-day protocol.

Centralises the distance-specific data that used to live in five parallel
dicts in `race_protocol_generator` (display name, pacing strategy,
nutrition timing, mental checkpoints, race-morning timeline, week-before
extras). Adding a new road race distance is now one registry entry rather
than five scattered dict updates.

Trail / ultra protocols remain procedurally generated by
`race_protocol_generator` (their content scales with distance, elevation,
and predicted duration). Trail still consumes
`RACE_PROFILES[30.0].pacing_strategy` as the base copy plus its own
bracket-specific extras.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Dict, List, Tuple


@dataclass(frozen=True)
class RaceProfile:
    """Distance-specific race-day content.

    `distance_km` is the canonical race distance.
    `display_name` is the user-facing label ("5K", "Half Marathon", …).
    `pacing_strategy` is the prose paragraph rendered in the race-day card.
    `nutrition_timing` / `mental_checkpoints` / `morning_timeline` /
    `week_before_extras` are the per-section payloads consumed by the
    template.
    """
    distance_km: float
    display_name: str
    pacing_strategy: str
    nutrition_timing: List[Dict[str, str]]
    mental_checkpoints: List[Dict[str, str]]
    morning_timeline: List[Tuple[str, str]]
    week_before_extras: List[str] = field(default_factory=list)


